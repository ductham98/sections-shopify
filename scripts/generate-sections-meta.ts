import fs from "fs";
import path from "path";
import { discoverAllSections } from "../src/lib/section-discovery";

function main() {
  const rootDir = process.cwd();
  const sectionsDir = path.join(rootDir, "sections");
  const outputDir = path.join(rootDir, "src", "generated");
  const outputFile = path.join(outputDir, "sections-meta.generated.ts");

  console.log(`[generate-sections-meta] Scanning sections from: ${sectionsDir}`);
  const { sections, sources } = discoverAllSections(sectionsDir);

  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  const generatedCode = `/**
 * AUTO-GENERATED FILE — DO NOT EDIT MANUALLY.
 * Generated by scripts/generate-sections-meta.ts
 * Run \`npm run sections:generate\` to refresh.
 */

import { DiscoveredSectionMeta } from "@/lib/section-discovery";

export const GENERATED_AT = ${JSON.stringify(new Date().toISOString())};

export const DISCOVERED_SECTIONS: DiscoveredSectionMeta[] = ${JSON.stringify(sections, null, 2)};

export const SECTION_SOURCES: Record<string, string> = ${JSON.stringify(sources, null, 2)};

export function getDiscoveredSections(): DiscoveredSectionMeta[] {
  return DISCOVERED_SECTIONS;
}

export function getGeneratedSectionSource(id: string): string | null {
  return SECTION_SOURCES[id] || null;
}
`;

  fs.writeFileSync(outputFile, generatedCode, "utf-8");
  console.log(`[generate-sections-meta] Successfully generated: ${outputFile}`);
  console.log(`[generate-sections-meta] Total sections discovered: ${sections.length}`);

  // Summary by category
  const catSummary: Record<string, number> = {};
  sections.forEach((s) => {
    catSummary[s.category] = (catSummary[s.category] || 0) + 1;
  });
  console.log("[generate-sections-meta] Categories breakdown:", catSummary);
}

main();

